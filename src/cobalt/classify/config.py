"""The trial's config family: `configs/cobalt/classify/trial.yaml` (L10).

Pydantic schema, in git, with a dry-run (`cobalt classify trial --dry-run`).
A bad file crashes; there is no built-in default for anything here —
`notify/config.py`'s loader shape.

WHERE THE FILE LIVES AND WHY. `configs/cobalt/` is outside the old
loader's top-level `configs/*.yaml` glob (CLAUDE.md config boundary), and
the `classify/` subdirectory keeps the trial's data in one place.

WHAT IS RULED AND SAYS SO. `model_id` and `spend_cap_usd` are Dejan's
values (`cto-2026-09-23.md` R42); each carries a `*_source` naming the
ruling, and a source that does not start `ruling:` refuses to load (L53:
a ceiling is never settled silently in a config file). Discovery VERIFIES
the model id; it never replaces it.

THE SETS (plan §2). Items are declared, never generated by a model:
explicit constructed items, plus four declarative derivations the loader
applies deterministically — `padding` (FLOOR's ≈300 / ≈1,500-token
states, words repeated to size), `injection_twins` (S1's control items),
`shuffled_twin` (S3's key-order twins, a seeded shuffle), `compose` (L20's
headline × context states). T9 is a glob resolved AT RUN TIME over
Cobalt's committed day-open reports — never copied text.
"""

from __future__ import annotations

import json
import random
from pathlib import Path
from typing import Literal, Optional, Union
from urllib.parse import urlparse

import yaml
from pydantic import BaseModel, ConfigDict, Field, ValidationError, field_validator

from .models import Question, QuestionSet, TrialItem

REPO_ROOT = Path(__file__).resolve().parents[3]
CONFIG_PATH = REPO_ROOT / "configs" / "cobalt" / "classify" / "trial.yaml"

SET_NAMES = ("FLOOR", "S1", "S2", "S3", "T9", "L20")

#: The one host this package talks to (plan §6).
ALLOWED_HOST = "openrouter.ai"


class ClassifyConfigError(RuntimeError):
    """Missing/invalid trial config — crash, never fall back."""


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class ItemSpec(_Strict):
    id: str = Field(min_length=1)
    state: Union[str, dict[str, str]]


class Padding(_Strict):
    """Constructed filler states of a target size (plan M2). `base` is
    repeated word by word until chars ÷ 4 reaches each target — the same
    ÷ 4 estimate the dry-run states."""

    base: str = Field(min_length=1)
    target_tokens: list[int] = Field(min_length=1)


class InjectionTwins(_Strict):
    """The first `count` items again, each with `suffix` appended — the
    control for text that argues for its own label (broad T2)."""

    count: int = Field(ge=1)
    suffix: str = Field(min_length=1)


class ShuffledTwin(_Strict):
    """The first `count` dict-state items again with their keys in a
    seeded shuffled order (deep §5 S3: order sensitivity)."""

    count: int = Field(ge=1)
    seed: int


class Compose(_Strict):
    """`count` states, each = item i of `text_from` as `headline` plus
    the context words of item i of `context_from` (plan §2 L20)."""

    count: int = Field(ge=1)
    text_from: str
    context_from: str


class TrialSet(_Strict):
    version: int = Field(ge=1)
    questions_from: list[str] = Field(default_factory=list)
    questions: dict[str, Question] = Field(default_factory=dict)
    expect_questions: Optional[int] = None
    items: list[ItemSpec] = Field(default_factory=list)
    items_from: Optional[str] = None
    items_glob: Optional[str] = None
    padding: Optional[Padding] = None
    injection_twins: Optional[InjectionTwins] = None
    shuffled_twin: Optional[ShuffledTwin] = None
    compose: Optional[Compose] = None


class TrialConfig(_Strict):
    models_url: str
    door_url: str
    match_pattern: str = Field(min_length=1)
    model_id: str = Field(min_length=1)
    model_id_source: str
    door: Literal["", "systemone"] = ""
    entry_record: str = Field(min_length=1)
    timeout_s: float = Field(gt=0)
    max_parallel: int = Field(ge=1)
    call_ceiling: int = Field(ge=1)
    spend_cap_usd: float = Field(gt=0)
    spend_cap_source: str
    results_dir: str = Field(min_length=1)
    sets: dict[str, TrialSet]

    @field_validator("models_url", "door_url")
    @classmethod
    def _openrouter_only(cls, v: str) -> str:
        u = urlparse(v)
        if u.scheme != "https" or u.hostname != ALLOWED_HOST:
            raise ValueError(
                f"{v!r}: only https://{ALLOWED_HOST}/… is allowed — this package has "
                "one door and no other network path"
            )
        return v

    @field_validator("model_id_source", "spend_cap_source")
    @classmethod
    def _ruled(cls, v: str) -> str:
        if not v.startswith("ruling:"):
            raise ValueError(
                f"{v!r} must start 'ruling:' and name his row — a ruled value is "
                "never settled silently in a config file (L53)"
            )
        return v

    @field_validator("results_dir")
    @classmethod
    def _inside_scratch(cls, v: str) -> str:
        _scratch_path(v)
        return v

    @field_validator("sets")
    @classmethod
    def _all_sets(cls, v: dict[str, TrialSet]) -> dict[str, TrialSet]:
        if set(v) != set(SET_NAMES):
            raise ValueError(f"sets must be exactly {list(SET_NAMES)} (got {sorted(v)})")
        return v

    # -- resolution -------------------------------------------------------

    def results_path(self) -> Path:
        return _scratch_path(self.results_dir)

    def entry_pricing(self) -> dict:
        """The listed price of his model, from the committed per-model
        endpoints record (R3's real capture, L45). Exactly one endpoint
        with a `pricing` object, else FAILED — L1: no cost, no call."""
        path = REPO_ROOT / self.entry_record
        try:
            data = json.loads(path.read_text())["data"]
            (endpoint,) = data["endpoints"]
            pricing = endpoint["pricing"]
            if not isinstance(pricing, dict):
                raise TypeError("'pricing' is not an object")
        except Exception as e:  # noqa: BLE001
            raise ClassifyConfigError(
                f"entry_record {self.entry_record!r}: no single endpoint pricing "
                f"({type(e).__name__}: {e}) — L1: no cost, no call"
            ) from None
        return pricing

    def resolve(self, name: str) -> tuple[QuestionSet, list[TrialItem]]:
        """(question set, items) for one set name. Deterministic."""
        if name not in self.sets:
            raise ClassifyConfigError(f"unknown set {name!r} — known: {list(SET_NAMES)}")
        return self._questions(name), self._items(name)

    def _questions(self, name: str, _seen: tuple[str, ...] = ()) -> QuestionSet:
        if name in _seen:
            raise ClassifyConfigError(f"questions_from cycle: {' -> '.join((*_seen, name))}")
        spec = self.sets[name]
        merged: dict = {}
        for src in spec.questions_from:
            if src not in self.sets:
                raise ClassifyConfigError(f"{name}.questions_from names unknown set {src!r}")
            for qid, q in self._questions(src, (*_seen, name)).questions.items():
                if qid in merged:
                    raise ClassifyConfigError(f"{name}: question id {qid!r} appears twice")
                merged[qid] = q
        for qid, q in spec.questions.items():
            if qid in merged:
                raise ClassifyConfigError(f"{name}: question id {qid!r} appears twice")
            merged[qid] = q
        if not merged:
            raise ClassifyConfigError(f"{name}: no question")
        if spec.expect_questions is not None and len(merged) != spec.expect_questions:
            raise ClassifyConfigError(
                f"{name}: expect_questions {spec.expect_questions}, resolved {len(merged)}"
            )
        return QuestionSet(id=name, version=spec.version, questions=merged)

    def level_keys(self, name: str) -> list[list[str]]:
        """A layered set's question ids by level (plan M4): each
        `questions_from` set's ids in order, then the set's own. A set
        with no `questions_from` has no levels."""
        spec = self.sets[name]
        if not spec.questions_from:
            raise ClassifyConfigError(f"{name}: no levels (it has no questions_from)")
        levels = [list(self._questions(src).questions) for src in spec.questions_from]
        if spec.questions:
            levels.append(list(spec.questions))
        return levels

    def _declared(self, name: str) -> list[TrialItem]:
        """The explicit items of a set (or of the set it borrows from)."""
        spec = self.sets[name]
        if spec.items_from:
            if spec.items_from not in self.sets:
                raise ClassifyConfigError(f"{name}.items_from names unknown set {spec.items_from!r}")
            return self._declared(spec.items_from)
        return [TrialItem(id=i.id, state=i.state, provenance="constructed") for i in spec.items]

    def _items(self, name: str) -> list[TrialItem]:
        spec = self.sets[name]
        if spec.items_glob:
            return _glob_items(name, spec.items_glob)

        out = list(self._declared(name))

        if spec.padding:
            for target in spec.padding.target_tokens:
                out.append(TrialItem(
                    id=f"{name}-pad-{target}",
                    state=_pad(spec.padding.base, target),
                    provenance="constructed",
                ))

        if spec.injection_twins:
            base = self._declared(name)
            if spec.injection_twins.count > len(base):
                raise ClassifyConfigError(f"{name}: injection_twins.count exceeds its items")
            for it in base[: spec.injection_twins.count]:
                if not isinstance(it.state, str):
                    raise ClassifyConfigError(f"{name}: injection twins need text states")
                out.append(TrialItem(
                    id=f"{it.id}-inj",
                    state=f"{it.state} {spec.injection_twins.suffix}",
                    provenance="constructed",
                ))

        if spec.shuffled_twin:
            base = self._declared(name)
            if spec.shuffled_twin.count > len(base):
                raise ClassifyConfigError(f"{name}: shuffled_twin.count exceeds its items")
            rng = random.Random(spec.shuffled_twin.seed)
            for it in base[: spec.shuffled_twin.count]:
                if not isinstance(it.state, dict):
                    raise ClassifyConfigError(f"{name}: shuffled twins need dict states")
                keys = list(it.state)
                shuffled = keys[:]
                rng.shuffle(shuffled)
                if shuffled == keys:          # a shuffle that moved nothing is no twin
                    shuffled = keys[1:] + keys[:1]
                out.append(TrialItem(
                    id=f"{it.id}-shuf",
                    state={k: it.state[k] for k in shuffled},
                    provenance="constructed",
                ))

        if spec.compose:
            c = spec.compose
            texts, contexts = self._declared(c.text_from), self._declared(c.context_from)
            if c.count > len(texts) or not contexts:
                raise ClassifyConfigError(f"{name}: compose.count exceeds {c.text_from}'s items")
            for i in range(c.count):
                t, ctx = texts[i], contexts[i % len(contexts)]
                if not isinstance(t.state, str) or not isinstance(ctx.state, dict):
                    raise ClassifyConfigError(f"{name}: compose needs text × dict states")
                out.append(TrialItem(
                    id=f"{name}-{t.id}-{ctx.id}",
                    state={"headline": t.state, **ctx.state},
                    provenance="constructed",
                ))

        if not out:
            raise ClassifyConfigError(f"{name}: no item — L1: never an empty set")
        return out


def _scratch_path(results_dir: str) -> Path:
    scratch = (REPO_ROOT / "scratch").resolve()
    p = (REPO_ROOT / results_dir).resolve()
    if p != scratch and scratch not in p.parents:
        raise ValueError(
            f"results_dir {results_dir!r} resolves to {p}, outside {scratch} — results "
            "live in the worktree's scratch/ only (not the vault, not the DB, not git)"
        )
    return p


def _pad(base: str, target_tokens: int) -> str:
    words = base.split()
    out: list[str] = []
    i = 0
    while len(" ".join(out)) < target_tokens * 4:
        out.append(words[i % len(words)])
        i += 1
    return " ".join(out)


def _glob_items(name: str, pattern: str) -> list[TrialItem]:
    paths = sorted(REPO_ROOT.glob(pattern))
    if not paths:
        raise ClassifyConfigError(
            f"{name}: items_glob {pattern!r} matched nothing under {REPO_ROOT} — L1"
        )
    return [
        TrialItem(
            id=p.stem,
            state=p.read_text(),
            provenance=f"real:{p.relative_to(REPO_ROOT).as_posix()}",
        )
        for p in paths
    ]


def load_trial_config(path: Optional[Path] = None) -> TrialConfig:
    path = Path(path) if path is not None else CONFIG_PATH
    if not path.exists():
        raise ClassifyConfigError(
            f"trial config not found: {path}. There is no built-in default."
        )
    try:
        raw = yaml.safe_load(path.read_text())
    except yaml.YAMLError as e:
        raise ClassifyConfigError(f"{path}: YAML does not parse:\n{e}") from None
    if not isinstance(raw, dict) or "classify" not in raw:
        raise ClassifyConfigError(f"{path}: expected a 'classify' mapping")
    try:
        return TrialConfig(**raw["classify"])
    except ValidationError as e:
        raise ClassifyConfigError(f"{path}: invalid trial config:\n{e}") from None


